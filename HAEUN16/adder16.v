// ============================================================================
// adder16.v - HAEUN-16 16비트 가산기
// ============================================================================
// 기능: SUM = A + B (16비트 덧셈, 자리올림은 COUT으로 출력)
// 합성: Verilog-2001, FPGA 이식 가능 (조합 논리)
// ============================================================================

module adder16 (
    input  wire [15:0] A,      // 피가수 (Operand A)
    input  wire [15:0] B,      // 피더수 (Operand B)
    output wire [15:0] SUM,    // 16비트 합 (하위 16비트)
    output wire        COUT   // 자리올림 (17번째 비트, 1 = 오버플로)
);

    // 17비트 확장 덧셈: {COUT, SUM} = A + B
    // COUT=1 이면 16비트 범위를 넘는 합 (예: 65535 + 1)
    assign {COUT, SUM} = A + B;

endmodule
